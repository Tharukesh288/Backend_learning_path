def test_create_book(db):

    # --------------------------------------------------------
    # Create an Author first
    # --------------------------------------------------------
    #
    # Book requires:
    #
    #     author_id = ForeignKey("author.id")
    #
    # So we need an author before creating a book.

    test_author = Author(name="Test Author")

    # Add author to TEST database
    db.add(test_author)

    # Save author
    db.commit()

    # Get the ID generated by the database
    db.refresh(test_author)


    # --------------------------------------------------------
    # Create Book request data
    # --------------------------------------------------------

    book = {
        "title": "Test Book",

        # Don't assume author_id = 1.
        # Use the ID that the test database actually generated.
        "author_id": test_author.id,

        "pages": 300,
        "price": 500
    }


    # Send POST request to FastAPI
    response = client.post(
        "/books/",
        json=book
    )


    # API should successfully create the book
    assert response.status_code == 200

def test_get_book_by_id(db):

    # Create an author
    author = Author(name="Test Author")

    db.add(author)
    db.commit()
    db.refresh(author)

    # Create a book through the API
    book = {
        "title": "Test Book",
        "author_id": author.id,
        "pages": 300,
        "price": 500
    }

    create_response = client.post("/books/", json=book)

    assert create_response.status_code == 200

    # Get the ID assigned to the new book
    book_id = create_response.json()["id"]

    # Now request that specific book
    response = client.get(f"/books/{book_id}")

    # It should exist
    assert response.status_code == 200

    # Check that we got the correct book
    assert response.json()["title"] == "Test Book"

