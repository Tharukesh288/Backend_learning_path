# ============================================================
# 1. CREATE TEST DATABASE
# ============================================================

# This is a SEPARATE database from your real books.db
TEST_DATABASE_URL = "sqlite:///test_book.db"


# Create an engine connected to the test database
test_engine = create_engine(
    TEST_DATABASE_URL,

    # Required for SQLite when used with FastAPI/TestClient
    connect_args={"check_same_thread": False}
)


# Create database sessions that use test_book.db
TestingSessionLocal = sessionmaker(
    autocommit=False,
    autoflush=False,
    bind=test_engine
)


# Create all SQLAlchemy tables inside test_book.db
#
# Your Base knows about:
#   Author
#   Book
#   User
#
# So these tables will be created in the test database.
Base.metadata.create_all(bind=test_engine)


# ============================================================
# 2. DATABASE FIXTURE
# ============================================================

@pytest.fixture
def db():
    # Start with a clean database
    Base.metadata.drop_all(bind=test_engine)

    # Create fresh tables
    Base.metadata.create_all(bind=test_engine)

    # Create a database session
    db = TestingSessionLocal()

    try:
        # Give the test the fresh database
        yield db

    finally:
        # Close the session
        db.close()

        # Remove all test tables after the test
        Base.metadata.drop_all(bind=test_engine)


# ============================================================
# 3. OVERRIDE FASTAPI'S DATABASE DEPENDENCY
# ============================================================

def override_get_db():
    # Instead of using your normal sessionLocal,
    # create a session connected to test_book.db
    db = TestingSessionLocal()

    try:
        # Give FastAPI the TEST database session
        yield db

    finally:
        # Close it after the request finishes
        db.close()


# Tell FastAPI:
#
# Whenever the application asks for:
#     Depends(get_db)
#
# use:
#     override_get_db()
#
# instead.
app.dependency_overrides[get_db] = override_get_db


