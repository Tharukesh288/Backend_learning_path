def test_update_book(db):

    # Create an author first
    author = Author(name="Test Author")

    db.add(author)
    db.commit()
    db.refresh(author)

    # Create the original book
    book = {
        "title": "Original Book",
        "author_id": author.id,
        "pages": 200,
        "price": 300
    }

    create_response = client.post(
        "/books/",
        json=book
    )

    assert create_response.status_code == 200

    # Get the ID of the created book
    book_id = create_response.json()["id"]

    # Data we want to update
    updated_book = {
        "title": "Updated Book",
        "author_id": author.id,
        "pages": 500,
        "price": 750
    }

    # Send PUT request
    response = client.put(
        f"/books/{book_id}",
        json=updated_book
    )

    # Update should succeed
    assert response.status_code == 200

    # Verify the returned data
    data = response.json()

    assert data["title"] == "Updated Book"
    assert data["pages"] == 500
    assert data["price"] == 750

